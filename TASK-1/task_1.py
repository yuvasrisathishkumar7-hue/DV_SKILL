"""

df.head()

"""### **STEP 10: DISPLAY UNIQUE VALUES IN THE CATEGORY COLUMN**"""

df['Category'].unique()

"""### **STEP 11: CHECK FOR MISSING VALUES**"""

df.isnull().sum()

"""### **STEP 12: CALCULATE TOTAL SALES BY CATEGORY**"""

category_sales = (df.groupby('Category')['Sales'].sum())
category_sales

"""### **STEP 13: VISUALIZE TOTAL SALES BY CATEGORY**"""

category_sales.plot( kind='bar',figsize=(8,5),color='#C3B1E1')
