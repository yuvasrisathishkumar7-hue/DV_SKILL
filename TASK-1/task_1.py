"""### **STEP 7: VERIFY THE UPDATED DATA TYPES**"""

df.info()

"""### **STEP 8: CALCULATE DELIVERY DAYS**"""

df['Delivery Days'] = (df['Ship Date'] - df['Order Date']).dt.days

