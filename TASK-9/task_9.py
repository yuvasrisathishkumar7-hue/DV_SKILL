features = [
    'bedrooms',
    'bathrooms',
    'sqft_living',
    'grade',
    'yr_built'
]

print("Property Features:")
print(df[features].head())

"""**EXTRACT SALE YEAR**"""

df['sale_year'] = pd.to_datetime(
    df['date']
).dt.year

"""**CALCULATE PROPERTY AGE**"""

df['property_age'] = (
    df['sale_year'] - df['yr_built']
)

"""**CHECK RENOVATION STATUS**"""

df['is_renovated'] = np.where(
    df['yr_renovated'] > 0,
    'Yes',
    'No'
)

df[
    ['sale_year', 'is_renovated']
].head()

"""**CALCULATE PRICE PER SQUARE FOOT**"""

df['price_per_sqft'] = (
    df['price'] / df['sqft_living']
)

df[
    ['price', 'sqft_living', 'price_per_sqft']
].head()

"""**CONVERT DATE COLUMN**"""

df['date'] = pd.to_datetime(
    df['date'],
    errors='coerce'
)

"""**EXTRACT SALE YEAR**"""

df['sale_year'] = df['date'].dt.year

"""**CALCULATE AGE AT SALE**"""

df['age_at_sale'] = (
    df['sale_year'] - df['yr_built']
)

"""**CALCULATE YEARS SINCE RENOVATION**"""

df['years_since_renovation'] = np.where(
    df['yr_renovated'].notna() &
    (df['yr_renovated'] > 0),
    df['sale_year'] - df['yr_renovated'],
    0
)

"""**DISPLAY DATE AND AGE DETAILS**"""

df[
    [
        'date',
        'sale_year',
        'yr_built',
        'age_at_sale',
        'yr_renovated',
        'years_since_renovation'
    ]
].head()

"""**CALCULATE PRICE PER SQUARE FOOT OF LIVING AREA**"""

df['price_per_sqft_living'] = (
    df['price'] / df['sqft_living']
)

"""**CALCULATE PRICE PER SQUARE FOOT OF LOT AREA**"""

df['price_per_sqft_lot'] = (
    df['price'] / df['sqft_lot']
)

"""**DISPLAY PRICE AND AREA DETAILS**"""

df[
    ['price', 'sqft_living', 'sqft_lot']
].head()

"""**BOX PLOT OF PRICE PER SQUARE FOOT OF LIVING AREA**"""

plt.figure(figsize=(10, 5))

sns.boxplot(data=df['price_per_sqft_living'])

plt.title('Box Plot of Price per Square Foot')
plt.show()

"""**BOX PLOT OF PRICE PER SQUARE FOOT OF LOT AREA**"""

plt.figure(figsize=(10, 5))

sns.boxplot(data=df['price_per_sqft_lot'])

